/**
 * Provider-backed session ownership and the local advisory-lock implementation
 * shared by the first-party persistence backends.
 * @module @deepseek-ai/dsh-session-persistence/ownership
 */

import { createHash, randomBytes } from 'node:crypto'
import { open, mkdir, readFile, rename, rm } from 'node:fs/promises'
import type { FileHandle } from 'node:fs/promises'
import { dirname, join, toNamespacedPath } from 'node:path'
import type { Branded } from '@deepseek-ai/dsh-brand'
import type { SessionId } from '@deepseek-ai/dsh-session'

/** Opaque identity chosen once by one server incarnation. */
export type SessionOwnerToken = Branded<'SessionOwnerToken'>

/**
 * Brand an owner identity generated by a trusted same-process caller.
 * @param value - stable owner-incarnation identity.
 * @returns the branded identity.
 */
export function SessionOwnerToken(value: string): SessionOwnerToken {
  return value as SessionOwnerToken
}

/** Monotonic decimal generation assigned under a session's ownership guard. */
export type SessionFencingToken = Branded<'SessionFencingToken'>

/**
 * Brand a provider-issued decimal fencing generation.
 * @param value - decimal generation persisted by the provider.
 * @returns the branded fencing token.
 */
export function SessionFencingToken(value: string): SessionFencingToken {
  return value as SessionFencingToken
}

/** Another process or provider instance currently owns the session guard. */
export class SessionOwnershipConflictError extends Error {
  /**
   * @param sessionId - contended session identity.
   */
  constructor(readonly sessionId: SessionId) {
    super(`session "${sessionId}" already has an active ownership`)
    this.name = 'SessionOwnershipConflictError'
  }
}

/** A fenced session was mutated without the provider instance that owns it. */
export class SessionOwnershipRequiredError extends Error {
  /**
   * @param sessionId - session whose persistent ownership marker was observed.
   */
  constructor(readonly sessionId: SessionId) {
    super(`session "${sessionId}" requires an active ownership in this persistence provider`)
    this.name = 'SessionOwnershipRequiredError'
  }
}

/** A released ownership handle was used again. */
export class SessionOwnershipLostError extends Error {
  /**
   * @param sessionId - session formerly owned by the handle.
   */
  constructor(readonly sessionId: SessionId) {
    super(`session "${sessionId}" ownership is no longer active`)
    this.name = 'SessionOwnershipLostError'
  }
}

/**
 * One process-held session ownership. There is no expiry: the native advisory
 * lock remains held until release, provider teardown, or process death.
 */
export interface SessionOwnership extends AsyncDisposable {
  /** Session protected by this ownership. */
  readonly sessionId: SessionId
  /** Caller-chosen owner incarnation. */
  readonly ownerToken: SessionOwnerToken
  /** Provider-issued monotonic generation. */
  readonly fencingToken: SessionFencingToken
  /** Whether this handle still admits guarded mutations and execution. */
  readonly active: boolean
  /** Reject after release has begun. */
  assertActive(): void
  /** Drain guarded mutations, release the native lock, and invalidate this handle. */
  release(): Promise<void>
  /** Alias of {@link release} for `await using`. */
  [Symbol.asyncDispose](): Promise<void>
}

interface NativeAdvisoryLock {
  readonly active: boolean
  release(): Promise<void>
}

type Win32Pointer = bigint | null

interface Win32LockBindings {
  createFileW(path: string, access: number, share: number, security: null, creation: number, flags: number, template: null): Win32Pointer
  lockFileEx(handle: Win32Pointer, flags: number, reserved: number, low: number, high: number, overlapped: unknown): number
  unlockFileEx(handle: Win32Pointer, reserved: number, low: number, high: number, overlapped: unknown): number
  closeHandle(handle: Win32Pointer): number
  moveFileExW(existing: string, replacement: string, flags: number): number
  getLastError(): number
  allocOverlapped(): unknown
}

const ERROR_LOCK_VIOLATION = 33
const GENERIC_READ = 0x80000000
const GENERIC_WRITE = 0x40000000
const FILE_SHARE_READ = 0x00000001
const FILE_SHARE_WRITE = 0x00000002
const OPEN_ALWAYS = 4
const LOCKFILE_FAIL_IMMEDIATELY = 0x1
const LOCKFILE_EXCLUSIVE_LOCK = 0x2
const MOVEFILE_REPLACE_EXISTING = 0x1
const MOVEFILE_WRITE_THROUGH = 0x8

let win32Bindings: Win32LockBindings | undefined

/** Load only the Win32 calls needed for one crash-released byte-range lock. */
async function loadWin32Bindings(): Promise<Win32LockBindings> {
  if (win32Bindings !== undefined) return win32Bindings
  const koffi = (await import('koffi')).default
  const kernel32 = koffi.load('kernel32.dll')
  const pointer = koffi.pointer('void')
  const createFileW = kernel32.func('__stdcall', 'CreateFileW', pointer, [
    'str16', 'uint32', 'uint32', pointer, 'uint32', 'uint32', pointer,
  ]) as Win32LockBindings['createFileW']
  const lockFileEx = kernel32.func('__stdcall', 'LockFileEx', 'int', [
    pointer, 'uint32', 'uint32', 'uint32', 'uint32', pointer,
  ]) as Win32LockBindings['lockFileEx']
  const unlockFileEx = kernel32.func('__stdcall', 'UnlockFileEx', 'int', [
    pointer, 'uint32', 'uint32', 'uint32', pointer,
  ]) as Win32LockBindings['unlockFileEx']
  const closeHandle = kernel32.func('__stdcall', 'CloseHandle', 'int', [pointer]) as Win32LockBindings['closeHandle']
  const moveFileExW = kernel32.func('__stdcall', 'MoveFileExW', 'int', [
    'str16', 'str16', 'uint32',
  ]) as Win32LockBindings['moveFileExW']
  const getLastError = kernel32.func('__stdcall', 'GetLastError', 'uint32', []) as Win32LockBindings['getLastError']
  win32Bindings = {
    createFileW,
    lockFileEx,
    unlockFileEx,
    closeHandle,
    moveFileExW,
    getLastError,
    allocOverlapped: (): unknown => koffi.alloc('uint8', 3 * koffi.sizeof('void *') + 8) as unknown,
  }
  return win32Bindings
}

function invalidWin32Handle(handle: Win32Pointer): boolean {
  return handle === null || handle === 0n || handle === -1n || handle === 0xFFFFFFFFFFFFFFFFn
}

/** Native Windows ownership guard; closing the handle releases it after a crash. */
class Win32AdvisoryLock implements NativeAdvisoryLock {
  private held = true

  constructor(
    private readonly bindings: Win32LockBindings,
    private readonly handle: Win32Pointer,
    private readonly overlapped: unknown,
    private readonly path: string,
  ) {}

  get active(): boolean {
    return this.held
  }

  release(): Promise<void> {
    try {
      if (!this.held) return Promise.resolve()
      this.held = false
      const unlocked = this.bindings.unlockFileEx(this.handle, 0, 1, 0, this.overlapped)
      const unlockCode = unlocked === 0 ? this.bindings.getLastError() : undefined
      const closed = this.bindings.closeHandle(this.handle)
      if (unlockCode !== undefined) {
        return Promise.reject(
          new Error(`UnlockFileEx failed for session ownership guard "${this.path}" (Win32 ${unlockCode})`),
        )
      }
      if (closed === 0) {
        const closeCode = this.bindings.getLastError()
        return Promise.reject(
          new Error(`CloseHandle failed for session ownership guard "${this.path}" (Win32 ${closeCode})`),
        )
      }
      return Promise.resolve()
    } catch (error: unknown) {
      return Promise.reject(error instanceof Error
        ? error
        : new Error('native session ownership release failed', { cause: error }))
    }
  }
}

interface PosixLockBindings {
  flock(fd: number, operation: number): number
  errno(): number
}

let posixBindings: PosixLockBindings | undefined

/** Load `flock(2)` from the host C library. */
async function loadPosixBindings(): Promise<PosixLockBindings> {
  if (posixBindings !== undefined) return posixBindings
  const koffi = (await import('koffi')).default
  const library = process.platform === 'darwin'
    ? 'libSystem.B.dylib'
    : process.platform === 'freebsd' || process.platform === 'openbsd'
      ? 'libc.so'
      : 'libc.so.6'
  const libc = koffi.load(library)
  posixBindings = {
    flock: libc.func('flock', 'int', ['int', 'int']) as PosixLockBindings['flock'],
    errno: () => koffi.errno(),
  }
  return posixBindings
}

/** POSIX ownership guard; closing the descriptor releases `flock` after a crash. */
class PosixAdvisoryLock implements NativeAdvisoryLock {
  private held = true

  constructor(
    private readonly bindings: PosixLockBindings,
    private readonly handle: FileHandle,
    private readonly path: string,
  ) {}

  get active(): boolean {
    return this.held
  }

  async release(): Promise<void> {
    if (!this.held) return
    this.held = false
    const unlocked = this.bindings.flock(this.handle.fd, 8)
    const unlockErrno = unlocked === 0 ? undefined : this.bindings.errno()
    await this.handle.close()
    if (unlockErrno !== undefined) {
      throw new Error(`flock(LOCK_UN) failed for session ownership guard "${this.path}" (errno ${unlockErrno})`)
    }
  }
}

/** Try one native, non-waiting lock acquisition. */
async function tryAcquireNative(path: string): Promise<NativeAdvisoryLock | undefined> {
  await mkdir(dirname(path), { recursive: true, mode: 0o700 })
  if (process.platform === 'win32') {
    const bindings = await loadWin32Bindings()
    const handle = bindings.createFileW(
      path,
      GENERIC_READ | GENERIC_WRITE,
      FILE_SHARE_READ | FILE_SHARE_WRITE,
      null,
      OPEN_ALWAYS,
      0,
      null,
    )
    if (invalidWin32Handle(handle)) {
      const code = bindings.getLastError()
      throw new Error(`CreateFileW failed for session ownership guard "${path}" (Win32 ${code})`)
    }
    const overlapped = bindings.allocOverlapped()
    if (bindings.lockFileEx(
      handle,
      LOCKFILE_EXCLUSIVE_LOCK | LOCKFILE_FAIL_IMMEDIATELY,
      0,
      1,
      0,
      overlapped,
    ) !== 0) {
      return new Win32AdvisoryLock(bindings, handle, overlapped, path)
    }
    const code = bindings.getLastError()
    bindings.closeHandle(handle)
    if (code === ERROR_LOCK_VIOLATION) return undefined
    throw new Error(`LockFileEx failed for session ownership guard "${path}" (Win32 ${code})`)
  }

  const handle = await open(path, 'a+', 0o600)
  const bindings = await loadPosixBindings()
  if (bindings.flock(handle.fd, 2 | 4) === 0) return new PosixAdvisoryLock(bindings, handle, path)
  const errno = bindings.errno()
  await handle.close()
  const contentionErrno = process.platform === 'linux' ? 11 : 35
  if (errno === contentionErrno) return undefined
  throw new Error(`flock(LOCK_EX|LOCK_NB) failed for session ownership guard "${path}" (errno ${errno})`)
}

function isENOENT(error: unknown): boolean {
  return (error as NodeJS.ErrnoException | null)?.code === 'ENOENT'
}

/** Read and validate the persisted decimal fence, allowing initial absence. */
async function readFence(path: string): Promise<bigint | undefined> {
  try {
    const stored = (await readFile(path, 'utf8')).trim()
    if (!/^(0|[1-9][0-9]*)$/.test(stored)) {
      throw new Error(`corrupt session ownership fence at "${path}"`)
    }
    return BigInt(stored)
  } catch (error: unknown) {
    if (isENOENT(error)) return undefined
    throw error
  }
}

/** Advance one durable decimal fence while the matching guard is held. */
async function advanceFence(path: string): Promise<SessionFencingToken> {
  const current = await readFence(path) ?? 0n
  const next = current + 1n
  const temp = `${path}.${randomBytes(6).toString('hex')}.tmp`
  try {
    const handle = await open(temp, 'wx', 0o600)
    try {
      await handle.writeFile(`${next}\n`)
      await handle.sync()
    } finally {
      await handle.close()
    }
    if (process.platform === 'win32') {
      const bindings = await loadWin32Bindings()
      const moved = bindings.moveFileExW(
        toNamespacedPath(temp),
        toNamespacedPath(path),
        MOVEFILE_REPLACE_EXISTING | MOVEFILE_WRITE_THROUGH,
      )
      if (moved === 0) {
        const code = bindings.getLastError()
        throw new Error(`MoveFileExW failed for session ownership fence "${path}" (Win32 ${code})`)
      }
    } else {
      await rename(temp, path)
      const directory = await open(dirname(path), 'r')
      try {
        await directory.sync()
      } finally {
        await directory.close()
      }
    }
  } catch (error: unknown) {
    await rm(temp, { force: true })
    throw error
  }
  return SessionFencingToken(String(next))
}

/** Concrete ownership handle retained by one registry. */
class FileSessionOwnership implements SessionOwnership {
  private phase: 'active' | 'releasing' | 'released' = 'active'
  private releaseTask: Promise<void> | undefined
  private readonly mutations = new Set<Promise<unknown>>()

  constructor(
    readonly sessionId: SessionId,
    readonly ownerToken: SessionOwnerToken,
    readonly fencingToken: SessionFencingToken,
    private readonly native: NativeAdvisoryLock,
    private readonly fencePath: string,
    private readonly onReleased: () => void,
  ) {}

  get active(): boolean {
    return this.phase === 'active' && this.native.active
  }

  assertActive(): void {
    if (!this.active) throw new SessionOwnershipLostError(this.sessionId)
  }

  /** Run one provider mutation without allowing release to unlock underneath it. */
  run<T>(operation: () => Promise<T> | T): Promise<T> {
    this.assertActive()
    const mutation = (async (): Promise<T> => {
      const current = await readFence(this.fencePath)
      if (current === undefined || current !== BigInt(this.fencingToken)) {
        throw new SessionOwnershipLostError(this.sessionId)
      }
      return operation()
    })()
    this.mutations.add(mutation)
    const forget = (): void => { this.mutations.delete(mutation) }
    void mutation.then(forget, forget)
    return mutation
  }

  release(): Promise<void> {
    this.releaseTask ??= this.releaseCore()
    return this.releaseTask
  }

  private async releaseCore(): Promise<void> {
    if (this.phase === 'released') return
    this.phase = 'releasing'
    await Promise.allSettled([...this.mutations])
    try {
      await this.native.release()
    } finally {
      this.phase = 'released'
      this.onReleased()
    }
  }

  [Symbol.asyncDispose](): Promise<void> {
    return this.release()
  }
}

/**
 * Provider-owned registry backed by one permanent guard file and one persistent
 * fence sidecar per session. Guard files are never unlinked: replacing a locked
 * inode would let two processes believe they own the same session. The fence
 * sidecar is also the durable marker that makes every later mutation require a
 * current local ownership.
 */
export class FileSessionOwnershipRegistry {
  private readonly ownerships = new Map<SessionId, FileSessionOwnership>()
  private readonly operations = new Set<Promise<unknown>>()
  private closed = false

  /**
   * @param root - backend-resolved private directory for ownership sidecars.
   */
  constructor(private readonly root: string) {}

  /**
   * Acquire and retain the exact session's native advisory guard.
   * @param sessionId - session identity whose guard is acquired.
   * @param ownerToken - stable identity of the caller/server incarnation.
   * @returns active ownership with a newly persisted fencing generation.
   */
  acquire(sessionId: SessionId, ownerToken: SessionOwnerToken): Promise<SessionOwnership> {
    if (this.closed) return Promise.reject(new Error('session ownership registry is closed'))
    const operation = this.acquireCore(sessionId, ownerToken)
    this.operations.add(operation)
    const forget = (): void => { this.operations.delete(operation) }
    void operation.then(forget, forget)
    return operation
  }

  private async acquireCore(sessionId: SessionId, ownerToken: SessionOwnerToken): Promise<SessionOwnership> {
    const retained = this.ownerships.get(sessionId)
    if (retained !== undefined) {
      if (retained.active && retained.ownerToken === ownerToken) return retained
      throw new SessionOwnershipConflictError(sessionId)
    }
    const paths = this.paths(sessionId)
    const native = await tryAcquireNative(paths.guard)
    if (native === undefined) throw new SessionOwnershipConflictError(sessionId)
    try {
      const fencingToken = await advanceFence(paths.fence)
      if (this.closed) throw new Error('session ownership registry is closed')
      const ownership = new FileSessionOwnership(
        sessionId,
        ownerToken,
        fencingToken,
        native,
        paths.fence,
        () => {
          if (this.ownerships.get(sessionId) === ownership) this.ownerships.delete(sessionId)
        },
      )
      this.ownerships.set(sessionId, ownership)
      return ownership
    } catch (error: unknown) {
      await native.release()
      throw error
    }
  }

  /**
   * Run an append or repair under this provider's active owner. Sessions that
   * have never enabled ownership retain the ordinary mutation path, serialized
   * against first acquisition by a short-lived guard.
   * @param sessionId - session whose mutation is being admitted.
   * @param operation - backend append or mutating repair to execute.
   * @returns the operation result after ownership and fence validation.
   */
  guardMutation<T>(sessionId: SessionId, operation: () => Promise<T> | T): Promise<T> {
    if (this.closed) return Promise.reject(new Error('session ownership registry is closed'))
    const ownership = this.ownerships.get(sessionId)
    if (ownership !== undefined) return ownership.run(operation)
    const guarded = this.guardUnownedMutation(sessionId, operation)
    this.operations.add(guarded)
    const forget = (): void => { this.operations.delete(guarded) }
    void guarded.then(forget, forget)
    return guarded
  }

  private async guardUnownedMutation<T>(sessionId: SessionId, operation: () => Promise<T> | T): Promise<T> {
    const paths = this.paths(sessionId)
    const native = await tryAcquireNative(paths.guard)
    if (native === undefined) throw new SessionOwnershipRequiredError(sessionId)
    try {
      try {
        await readFile(paths.fence, 'utf8')
        throw new SessionOwnershipRequiredError(sessionId)
      } catch (error: unknown) {
        if (!isENOENT(error)) throw error
      }
      return await operation()
    } finally {
      await native.release()
    }
  }

  /** Release every retained owner after in-flight guarded mutations settle. */
  async close(): Promise<void> {
    if (this.closed) return
    this.closed = true
    await Promise.allSettled([...this.operations])
    const results = await Promise.allSettled([...this.ownerships.values()].map(owner => owner.release()))
    const failures = results
      .filter((result): result is PromiseRejectedResult => result.status === 'rejected')
      .map(result => result.reason as unknown)
    if (failures.length > 0) throw new AggregateError(failures, 'session ownership registry close failed')
  }

  private paths(sessionId: SessionId): { guard: string; fence: string } {
    const digest = createHash('sha256').update(String(sessionId)).digest('hex')
    return {
      guard: join(this.root, `${digest}.guard`),
      fence: join(this.root, `${digest}.fence`),
    }
  }
}
